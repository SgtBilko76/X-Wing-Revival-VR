#!/usr/bin/env python3
"""Generate no-op stubs for the headless dedicated server build.

The dedicated server (xwingrev -dedicated) never touches graphics, sound, fonts or images,
but the engine's objects still reference those libraries. Instead of linking libGL/GLEW/
SDL_mixer/SDL_ttf/SDL_image on a headless box, resolve every such undefined symbol with a
no-op stub (returns 0 / NULL). Usage: gen_server_stubs.py <out.c> <obj.o>...
"""
import re
import subprocess
import sys

STUB_PREFIXES = ("gl", "__glew", "glew", "Mix_", "TTF_", "IMG_")

out_path, objects = sys.argv[1], sys.argv[2:]
undefined, defined = set(), set()
for obj in objects:
	text = subprocess.run(["nm", "-P", obj], check=True, capture_output=True, text=True).stdout
	for line in text.splitlines():
		parts = line.split()
		if len(parts) < 2:
			continue
		name, kind = parts[0], parts[1]
		if kind == "U":
			undefined.add(name)
		elif kind not in ("w", "v"):
			defined.add(name)

stubs = sorted(n for n in undefined - defined if n.startswith(STUB_PREFIXES) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n))
with open(out_path, "w") as f:
	f.write("/* Generated by tools/gen_server_stubs.py: no-op graphics/audio stubs for the dedicated server. */\n")
	f.write("#include <stddef.h>\n")
	for n in stubs:
		if n.startswith("__glew") or n.startswith("GLEW_"):
			f.write(f"void *{n} = NULL;\n")   # GLEW function pointers / extension flags
		else:
			f.write(f"long {n}(void) {{ return 0; }}\n")
print(f"gen_server_stubs: {len(stubs)} stubs")
